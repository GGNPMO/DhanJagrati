/** Single-name masters: Salutation, Occupation, Religion ... */
function simple(entity: string, title: string, nameKey: string, label: string, maxLength: number, extra: FieldConfig[] = []): MasterConfig {
  return {
    entity,
    title,
    formTitle: `Add ${title}`,
    listTitle: `${title} List`,
    fields: [{ name: nameKey, label, type: 'text', required: true, maxLength, span: 12 }, ...extra, active],
    columns: [
      { key: 'id', label: 'Id' },
      { key: nameKey, label },
      ...extra.map((f) => ({ key: f.name, label: f.label, type: f.type === 'bool' ? ('bool' as const) : undefined })),
      activeColumn,
    ],
  }
}

